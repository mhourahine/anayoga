<h1>What is Hemp?</h1>

<p>Industrial Hemp is an ancient crop that is made of strong fibres, four to six times stronger
than cotton!  It is a distinct variety of the plant species "Cannabis Sativa L." and is often
confused with marijuana because of the similar leaf shape.  Hemp contains virtually no THC
(delta 9 tetrahydrocannabinol), the active ingredient in marijuana. Marijuana typically contains
between 3 and 20% THC, while industrial hemp must contain no more than 0.3% to be legally cultivated
in Canada.

<p>Here are just a few reasons why hemp is the material of choice at <font class=anayoga>AnaYoga</font>:

<ul>
<li>Hemp requires no pesticides to aid in its growth, as it is naturally pest resistant.
<li>Hemp requires no herbicides because it is grown so densely that it smothers out other plants.
<li>Hemp requires little or no fertilizer.
<li>Hemp is a renewable resource.
<li>Hemp’s strong roots help control erosion, and it needs very little water to grow.
<li>One acre of hemp produces as much fibre as 4 acres of trees.
<li>Hemp grows to maturity in 100 days (versus trees which can take up to 100 years).
<li>The natural look of hemp is so great that no bleaching is required.  It is lightweight,
long-wearing, easy to clean and breathable.
</ul>

