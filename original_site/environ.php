<h1>AnaYoga and the Environment</h1>

<p>My number one concern is to create quality products with
as little negative impact to the environment as possible.
Here are some ways I have committed to this goal.

<p>Hemp and unbleached cotton fabrics are my materials of
choice in creating my products.  Click <a href=whatishemp.php>here</a> to learn
more about hemp’s wonderful properties.

<p>Little or no material is wasted.  For this reason, products
may vary slightly in size.  The sizes quoted are minimum dimensions.

<p>I avoid paper transactions whenever possible.  E-mail and
online ordering is encouraged.  “Hard-copy” or paper receipts
are given with orders only on request.  When paper is used,
those containing recycled fibres are favoured, despite their
higher cost to purchase.

<p>Bulk orders are encouraged through price incentives to cut
down on resources used for production, packaging and delivery
to the customer.

<p>To protect my products during shipping, a lot of packaging
is often necessary.  I encourage recycling and re-use, and provide self-addressed,
postage-paid envelopes for the return of certain packaging materials.  I then re-use these materials for subsequent orders.

<p>I am continually researching and evaluating my processes
for more environmentally-friendly solutions.  Have any
suggestions?  <a href="contact.php">Let me know!</a>




